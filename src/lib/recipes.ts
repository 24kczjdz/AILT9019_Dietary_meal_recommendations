import type {
  Aisle,
  Allergen,
  Art,
  DietTag,
  Ingredient,
  Kind,
  MealType,
  Recipe,
} from "@/lib/types";

function ing(
  key: string,
  name: string,
  quantity: number,
  unit: string,
  aisle: Aisle,
  macros: [number, number, number, number, number],
  allergens: Allergen[] = [],
  kinds: Kind[] = ["plant"],
): Ingredient {
  const [calories, protein, fat, carbs, fiber] = macros;
  return {
    key,
    name,
    quantity,
    unit,
    aisle,
    calories,
    protein,
    fat,
    carbs,
    fiber,
    allergens,
    kinds,
  };
}

export function deriveDiets(ingredients: Ingredient[]): DietTag[] {
  const allergens = new Set(ingredients.flatMap((item) => item.allergens));
  const kinds = new Set(ingredients.flatMap((item) => item.kinds));
  const meat = kinds.has("meat") || kinds.has("poultry") || kinds.has("pork");
  const fish = kinds.has("fish") || kinds.has("shellfish");
  const animal = meat || fish || kinds.has("dairy") || kinds.has("egg");
  const diets: DietTag[] = [];

  if (!meat && !fish) diets.push("vegetarian");
  if (!animal) diets.push("vegan");
  if (!meat) diets.push("pescatarian");
  if (!allergens.has("gluten")) diets.push("gluten-free");
  if (!allergens.has("dairy")) diets.push("dairy-free");
  if (!allergens.has("nuts") && !allergens.has("peanuts")) diets.push("nut-free");

  return diets;
}

type Draft = Omit<Recipe, "diets">;

function finish(draft: Draft): Recipe {
  return { ...draft, diets: deriveDiets(draft.ingredients) };
}

const oil = (grams: number): Ingredient =>
  ing(
    "olive-oil",
    "olive oil",
    grams,
    "g",
    "Pantry",
    [Math.round(grams * 8.8), 0, roundFat(grams), 0, 0],
  );

function roundFat(grams: number) {
  return Math.round(grams * 10) / 10;
}

